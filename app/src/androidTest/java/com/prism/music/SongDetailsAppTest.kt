package com.prism.music

import androidx.compose.ui.test.hasClickAction
import androidx.compose.ui.test.hasContentDescription
import androidx.compose.ui.test.hasParent
import androidx.compose.ui.test.hasText
import androidx.compose.ui.test.junit4.createEmptyComposeRule
import androidx.compose.ui.test.onFirst
import androidx.compose.ui.test.performClick
import androidx.compose.ui.test.performScrollTo
import androidx.compose.ui.test.performSemanticsAction
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.prism.music.data.db.PlayEventEntity
import com.prism.music.data.db.toEntity
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Song details (#211) from a song's menu, against player answers TYPED BY HAND in the shape YouTube was seen to send
 * ([SongFactsLiveTest] asks the real thing). What the answer lacks has no row, and asking failing isn't "nothing to say".
 */
@RunWith(AndroidJUnit4::class)
class SongDetailsAppTest {
    @get:Rule val compose = createEmptyComposeRule()
    @get:Rule val shots = ScreenshotOnFailure()

    private val c get() = Fixture.container
    private val song = Fixture.songs(1).first()

    @Before fun start() {
        RecordedNetwork.answers.clear()
        InstrumentationRegistry.getInstrumentation().uiAutomation.executeShellCommand("cmd media_session volume --stream 3 --set 0").close()
        Fixture.ready()
        Fixture.prismPlaylist("Everything", listOf(song))
    }

    @After fun end() {
        RecordedNetwork.answers.clear()
    }

    private fun answerPlayer(json: String) {
        RecordedNetwork.answers["https://www.youtube.com/youtubei/v1/player"] = json
        RecordedNetwork.answers["https://music.youtube.com/youtubei/v1/player"] = json
    }

    private fun openDetails() {
        Fixture.launch()
        compose.waitUntil(15_000) { compose.onAllNodes(hasText("Library") and hasClickAction()).fetchSemanticsNodes().isNotEmpty() }
        compose.onAllNodes(hasText("Library") and hasClickAction()).onFirst().performClick()
        compose.clickWhenFound(hasText("Everything") and hasClickAction(), 15_000)
        compose.clickWhenFound(hasContentDescription("More") and hasClickAction() and hasParent(hasText(song.title)), 15_000)
        val row = hasText("Song details") and hasClickAction()
        compose.waitUntil(10_000) { compose.onAllNodes(row).fetchSemanticsNodes().isNotEmpty() }
        compose.onAllNodes(row).onFirst().performScrollTo().performClick()
        // The sheet's own title, once the row that opened it has gone.
        compose.waitUntil(10_000) { compose.onAllNodes(row).fetchSemanticsNodes().isEmpty() }
    }

    private fun absent(text: String) = assertTrue("\"$text\" shouldn't show", compose.onAllNodes(hasText(text, substring = true)).fetchSemanticsNodes().isEmpty())

    @Test fun anAutoGeneratedSongShowsItsPlaysReleaseDateAndYours() {
        answerPlayer(
            """{"videoDetails":{"videoId":"${song.id}","viewCount":"1234567","shortDescription":"Provided to YouTube by Label\n\nReleased on: 2019-11-29\n\nAuto-generated by YouTube."},
              "microformat":{"playerMicroformatRenderer":{"publishDate":"2020-02-03T00:00:00-08:00"}}}""",
        )
        runBlocking {
            c.db.songs().upsert(song.toEntity())
            repeat(3) { c.db.plays().insert(PlayEventEntity(songId = song.id, timestamp = System.currentTimeMillis() - 3_600_000L * (it + 1), playedMs = 120_000)) }
        }
        openDetails()
        compose.waitForText("1,234,567", 15_000)
        compose.waitForText("PLAYS ON YOUTUBE MUSIC")
        compose.waitForText("November 29, 2019")
        compose.waitForText("YOUR PLAYS")
        // Released says when it came out; the upload's date isn't that, so it isn't shown beside it.
        absent("On YouTube since")
        absent("February")
    }

    @Test fun whatTheAnswerLeavesOutHasNoRow() {
        answerPlayer("""{"videoDetails":{"videoId":"${song.id}"},"microformat":{"playerMicroformatRenderer":{"publishDate":"2020-02-03T00:00:00-08:00"}}}""")
        openDetails()
        compose.waitForText("February 3, 2020", 15_000)
        compose.waitForText("ON YOUTUBE SINCE")
        absent("Plays on YouTube Music".uppercase())
        absent("RELEASED")
        absent("YOUR PLAYS")
    }

    /** YouTube can answer about another video for one it won't serve: that says nothing about this song. */
    @Test fun anAnswerAboutAnotherVideoSaysNothing() {
        answerPlayer("""{"videoDetails":{"videoId":"someoneElse","viewCount":"999"}}""")
        openDetails()
        compose.waitForText("YouTube shares no details", 15_000)
        absent("999")
    }

    /** The player's ⋯ has the same row, in the menu's own group, and opens the same sheet. */
    @Test fun thePlayersMenuHasItToo() {
        answerPlayer("""{"videoDetails":{"videoId":"${song.id}","viewCount":"1234567"}}""")
        Fixture.launch()
        val main = InstrumentationRegistry.getInstrumentation()
        main.runOnMainSync { c.player.playQueue(listOf(song), 0, com.prism.music.playback.QueueSource(com.prism.music.playback.QueueKind.OTHER, "Details test")) }
        Fixture.context.startActivity(
            android.content.Intent(android.content.Intent.ACTION_VIEW, android.net.Uri.parse("prism://player"))
                .setClass(Fixture.context, PrismActivity::class.java)
                .addFlags(android.content.Intent.FLAG_ACTIVITY_NEW_TASK or android.content.Intent.FLAG_ACTIVITY_SINGLE_TOP),
        )
        Thread.sleep(2_000)
        main.runOnMainSync { c.player.setPlaying(false) }
        compose.waitUntil(15_000) { compose.onAllNodes(androidx.compose.ui.test.hasTestTag("playerDeck")).fetchSemanticsNodes().isNotEmpty() }
        compose.onAllNodes(hasContentDescription(tr(R.string.song_options))).onFirst()
            .performSemanticsAction(androidx.compose.ui.semantics.SemanticsActions.OnClick)
        val row = hasText("Song details") and hasClickAction()
        compose.waitUntil(10_000) { compose.onAllNodes(row).fetchSemanticsNodes().isNotEmpty() }
        compose.onAllNodes(row).onFirst().performScrollTo().performClick()
        compose.waitForText("1,234,567", 15_000)
        compose.waitForText("PLAYS ON YOUTUBE MUSIC")
    }

    @Test fun failingToAskSaysSoAndNotThatThereIsNothing() {
        // No answer set: this suite's network has no recording of it, as a phone with no connection hasn't.
        openDetails()
        compose.waitForText("Couldn't ask YouTube", 15_000)
        absent("YouTube shares no details")
    }
}
