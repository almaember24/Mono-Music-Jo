package com.prism.music

import com.prism.music.data.innertube.SongFacts
import com.prism.music.ui.components.longDate
import com.prism.music.ui.components.wholeNumber
import kotlinx.serialization.json.Json
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.time.LocalDate
import java.util.Locale

/** #211: only what YouTube's answer really says, in the shapes its player answer takes (checked live 2026-11-05). */
class SongFactsTest {
    private fun parse(id: String, json: String) = SongFacts.parse(id, Json.parseToJsonElement(json))

    @Test
    fun anAutoGeneratedSongHasItsReleaseDateFromTheDescription() {
        val f = parse("a", """{"videoDetails":{"videoId":"a","viewCount":"4123456789",
            "shortDescription":"Provided to YouTube by Universal\n\nA Song · Someone\n\n℗ 2020 Label\n\nReleased on: 2019-11-29\n\nAuto-generated by YouTube."},
            "microformat":{"playerMicroformatRenderer":{"publishDate":"2019-11-28T21:01:00-08:00","uploadDate":"2019-11-28T21:01:00-08:00"}}}""")
        assertEquals(4123456789L, f.count)
        assertEquals(LocalDate.of(2019, 11, 29), f.releasedOn)
        // As YouTube wrote it: the date isn't moved by the phone's time zone.
        assertEquals(LocalDate.of(2019, 11, 28), f.publishedOn)
    }

    @Test
    fun aVideoHasNoReleaseDateEvenIfItsDescriptionTalksAboutOne() {
        val f = parse("v", """{"videoDetails":{"videoId":"v","viewCount":"900","shortDescription":"Our new album. Released on: 2019-11-29 everywhere!"},
            "microformat":{"playerMicroformatRenderer":{"publishDate":"2020-01-21"}}}""")
        assertNull(f.releasedOn)
        assertEquals(LocalDate.of(2020, 1, 21), f.publishedOn)
    }

    @Test
    fun youtubeMusicsOwnAnswerHasNoDescriptionButStillCounts() {
        val f = parse("a", """{"videoDetails":{"videoId":"a","viewCount":"12","musicVideoType":"MUSIC_VIDEO_TYPE_ATV"},
            "microformat":{"microformatDataRenderer":{"publishDate":"2019-11-28T21:01:00-08:00","viewCount":"12"}}}""")
        assertEquals(12L, f.count)
        assertNull(f.releasedOn)
        assertEquals(LocalDate.of(2019, 11, 28), f.publishedOn)
    }

    @Test
    fun whatIsMissingOrNonsenseIsLeftOut() {
        assertTrue(parse("a", """{"playabilityStatus":{"status":"LOGIN_REQUIRED","reason":"Sign in to confirm you're not a bot"}}""").isEmpty)
        assertTrue(parse("a", """{"videoDetails":{"videoId":"a","viewCount":"0"},"microformat":{"playerMicroformatRenderer":{"publishDate":"soon"}}}""").isEmpty)
        assertTrue(parse("a", """{"videoDetails":{"videoId":"a","viewCount":"lots","shortDescription":"Released on: yesterday"}}""").isEmpty)
    }

    @Test
    fun anAnswerAboutAnotherVideoSaysNothingAboutThisOne() {
        assertTrue(parse("a", """{"videoDetails":{"videoId":"other","viewCount":"5"}}""").isEmpty)
    }

    @Test
    fun oneAnswerFillsInWhatTheOtherLacks() {
        val web = SongFacts(releasedOn = LocalDate.of(2000, 1, 1))
        val music = SongFacts(count = 7, releasedOn = LocalDate.of(1999, 1, 1), publishedOn = LocalDate.of(2010, 1, 1))
        assertEquals(SongFacts(7, LocalDate.of(2000, 1, 1), LocalDate.of(2010, 1, 1)), web.orElse(music))
    }

    @Test
    fun numbersAndDatesAreWrittenAsTheLanguageDoes() {
        assertEquals("4,123,456", wholeNumber(4123456, Locale.US))
        assertEquals("4.123.456", wholeNumber(4123456, Locale.GERMANY))
        assertEquals("November 29, 2019", longDate(LocalDate.of(2019, 11, 29), Locale.US))
    }
}
